// Generates src/environments/firebase.config.ts from environment variables so the
// Firebase config is never committed. Runs automatically before start/build/test
// (npm "pre" scripts).
//
// Sources, in order of precedence:
//   1. Process environment (GitHub Actions secrets in CI)
//   2. A local .env file (git-ignored) — see .env.example
//
// Without values the app runs in "mock mode" (fake login, data in localStorage).
// Set FIREBASE_CONFIG_REQUIRED=true to fail instead (used by the deploy workflow,
// so production can never ship without a real config).

import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env');
const outFile = join(root, 'src/environments/firebase.config.ts');

if (existsSync(envFile)) {
  // Does not override variables already set in the environment
  process.loadEnvFile(envFile);
}

const fields = {
  apiKey: 'FIREBASE_API_KEY',
  authDomain: 'FIREBASE_AUTH_DOMAIN',
  projectId: 'FIREBASE_PROJECT_ID',
  storageBucket: 'FIREBASE_STORAGE_BUCKET',
  messagingSenderId: 'FIREBASE_MESSAGING_SENDER_ID',
  appId: 'FIREBASE_APP_ID',
  measurementId: 'FIREBASE_MEASUREMENT_ID',
};
const requiredFields = ['apiKey', 'authDomain', 'projectId', 'appId'];

const config = Object.fromEntries(
  Object.entries(fields).map(([key, envName]) => [key, (process.env[envName] ?? '').trim()])
);
const missing = requiredFields.filter(key => !config[key]).map(key => fields[key]);

if (missing.length && process.env.FIREBASE_CONFIG_REQUIRED === 'true') {
  console.error(`✘ Missing Firebase configuration: ${missing.join(', ')}`);
  console.error('  Add them as repository secrets (Settings → Secrets and variables → Actions).');
  process.exit(1);
}

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-firebase-config.mjs — do not edit or commit.\n` +
  `export const firebaseConfig = ${JSON.stringify(config, null, 2)};\n`
);

console.log(missing.length
  ? `⚠ Firebase config not set (${missing.join(', ')}): the app will run in mock mode.`
  : `✔ Firebase config generated for project "${config.projectId}".`);
